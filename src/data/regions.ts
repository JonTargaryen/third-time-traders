// Travel costs between adjacent regions (fuel consumption)
export const TRAVEL_COSTS: Record<string, number> = {
  default: 10,
  'delhi→jaisalmer': 12,
  'delhi→varanasi': 10,
  'delhi→hyderabad': 15,
  'kolkata→delhi': 14,
  'kolkata→varanasi': 8,
  'kolkata→bombay': 18,
  'jaisalmer→bombay': 15,
  'jaisalmer→hyderabad': 14,
  'varanasi→hyderabad': 12,
  'bombay→hyderabad': 10,
};

export function getTravelCost(from: RegionId, to: RegionId): number {
  const key1 = `${from}→${to}`;
  const key2 = `${to}→${from}`;
  return TRAVEL_COSTS[key1] ?? TRAVEL_COSTS[key2] ?? TRAVEL_COSTS.default;
}
